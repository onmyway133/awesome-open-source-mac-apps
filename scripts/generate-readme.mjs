#!/usr/bin/env node
// Writes README.md from categories.json and apps/*.json. Don't edit README.md by hand.
//
// Usage: node scripts/generate-readme.mjs [--check]   (--check exits 1 if README.md is out of date)

import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { root, loadApps, loadCategories } from './data.mjs'
import { MIN_STARS } from './github.mjs'

const formatStars = (n) => (n >= 1000 ? `${(n / 1000).toFixed(n >= 10000 ? 0 : 1).replace(/\.0$/, '')}k` : `${n}`)
const anchor = (name) => name.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/ /g, '-')
const cell = (text) => text.replace(/\|/g, '\\|')

const categories = loadCategories()
const apps = loadApps().map(({ slug, app }) => ({ slug, ...app }))
const sections = categories
  .map((category) => ({
    ...category,
    apps: apps.filter((a) => a.category === category.slug).sort((a, b) => (b.stars ?? 0) - (a.stars ?? 0) || a.name.localeCompare(b.name)),
  }))
  .filter((c) => c.apps.length > 0)

const lines = [
  '<!-- Generated by scripts/generate-readme.mjs from apps/*.json. Edit the JSON, not this file. -->',
  '',
  '# Awesome Open Source Mac Apps',
  '',
  `A curated list of ${apps.length} open source apps for macOS, each with at least ${MIN_STARS} GitHub stars.`,
  'Browse it with search and categories at [indiegoodies.com/awesome-open-source-mac-apps](https://indiegoodies.com/awesome-open-source-mac-apps).',
  '',
  '![](images/banner.png)',
  '',
  'Know a great app that is missing? [Add it with a pull request](CONTRIBUTING.md).',
  '',
  '## Contents',
  '',
  ...sections.map((c) => `- [${c.name}](#${anchor(c.name)}) (${c.apps.length})`),
  '',
]
for (const c of sections) {
  lines.push(`## ${c.name}`, '', `${c.description}.`, '', '| App | Stars | Description |', '|-----|------:|-------------|')
  for (const a of c.apps) {
    const links = [`[${cell(a.name)}](https://github.com/${a.repo})`]
    if (a.homepage) links.push(`[website](${a.homepage})`)
    lines.push(`| ${links.join(' · ')} | ${a.stars === undefined ? '' : `⭐ ${formatStars(a.stars)}`} | ${cell(a.description)} |`)
  }
  lines.push('')
}
lines.push('## Contributing', '', 'See [CONTRIBUTING.md](CONTRIBUTING.md).', '', '## License', '', 'CC0 1.0 Universal', '')

const readme = lines.join('\n')
const path = join(root, 'README.md')
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== readme) {
    console.error('README.md is out of date: run node scripts/generate-readme.mjs')
    process.exit(1)
  }
} else {
  writeFileSync(path, readme)
  console.log(`README.md: ${apps.length} apps in ${sections.length} categories.`)
}
